import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'chrome' })
const p = await b.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 })
await p.goto('http://127.0.0.1:8935/index.html', { waitUntil: 'networkidle' })
await p.waitForTimeout(1200)
await p.getByText('邮箱账户').first().click(); await p.waitForTimeout(1200)
// 聚焦发件服务器地址输入框，验证焦点态没有多层框
const smtp = p.locator('input[value="smtp.gmail.com"]').first()
await smtp.click().catch(() => {})
await p.waitForTimeout(400)
await p.screenshot({ path: '/tmp/fix_accounts.png' })
await p.getByText('下载记录').first().click(); await p.waitForTimeout(1000)
await p.locator('input').first().click().catch(() => {})
await p.waitForTimeout(300)
await p.screenshot({ path: '/tmp/fix_records.png' })
await b.close()
